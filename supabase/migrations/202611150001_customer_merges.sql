-- Customer Database: manual merge history. Additive only: no existing table, order, PV or commission is changed.
-- A merge row says "the customer of from_order_id is the same person as the customer of into_order_id".
-- Undo sets undone_at, so every merge stays in the history.
create table public.customer_merges (
  id bigint generated by default as identity primary key,
  from_order_id uuid not null references public.orders(id),
  into_order_id uuid not null references public.orders(id),
  created_at timestamptz not null default now(),
  undone_at timestamptz,
  check (from_order_id <> into_order_id)
);

alter table public.customer_merges enable row level security;
create policy "Authorized users manage customer merges" on public.customer_merges for all to authenticated
  using ((select public.is_app_user())) with check ((select public.is_app_user()));

-- Same API access pattern as orders: no anon access, no delete.
revoke all on public.customer_merges from anon, authenticated;
grant select, insert, update on public.customer_merges to authenticated;
